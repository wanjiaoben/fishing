// ── Helper: 按月份筛选 ──────────────────────────────────
function getPhotosByMonth(monthKey) {
  return PHOTOS.filter(p => p.month === monthKey);
}

// ── Helper: 获取所有月份列表 ───────────────────────────
function getAllMonths() {
  const months = [...new Set(PHOTOS.map(p => p.month))];
  return months.sort().reverse();
}

// ── Helper: 获取精选照片 ───────────────────────────────
function getFeaturedPhotos() {
  return PHOTOS.filter(p => p.featured);
}

// ── Helper: 获取Log照片 ────────────────────────────────
function getLogPhotos() {
  return PHOTOS.filter(p => p.showInLog).sort((a,b) => b.date.localeCompare(a.date));
}
